/**
 * Balance simulator (BRIEF section 13). Run with `npm run balance` (Vitest used as a TS runner).
 * Env: BAL_RUNS (seeds per cell, default 8), BAL_WEAPONS=all|sword,bow (per-weapon survival table),
 * BAL_CAP (seconds, default 1200). Writes docs/BALANCE_RESULTS.md.
 */
import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { WEAPON_IDS } from '../src/weapons';
import { type BotResult, type Policy, playRun } from './balance/bot';

const RUNS = Number(process.env['BAL_RUNS'] ?? 8);
const CAP = Number(process.env['BAL_CAP'] ?? 1200);
const WEAPON_FILTER = process.env['BAL_WEAPONS'] ?? 'all';

function stats(xs: number[]): { mean: number; median: number; p10: number; p90: number } {
  const s = [...xs].sort((a, b) => a - b);
  const at = (q: number): number => s[Math.min(s.length - 1, Math.floor(q * s.length))] ?? 0;
  return {
    mean: xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length),
    median: at(0.5),
    p10: at(0.1),
    p90: at(0.9),
  };
}

const mmss = (t: number): string =>
  `${Math.floor(t / 60)}:${String(Math.floor(t % 60)).padStart(2, '0')}`;

function row(label: string, rs: BotResult[]): string {
  const t = stats(rs.map((r) => r.time));
  const k = stats(rs.map((r) => r.kills));
  const lv = stats(rs.map((r) => r.level));
  const boss = rs.reduce((a, r) => a + r.bossKills, 0) / rs.length;
  const mini = rs.reduce((a, r) => a + r.miniKills, 0) / rs.length;
  const won = (100 * rs.filter((r) => r.won).length) / rs.length;
  return `| ${label} | ${mmss(t.median)} | ${mmss(t.p10)}–${mmss(t.p90)} | ${k.median.toFixed(0)} | ${lv.median.toFixed(0)} | ${boss.toFixed(1)} | ${mini.toFixed(1)} | ${won.toFixed(0)}% |`;
}

const HEAD =
  '| Cell | Median time | p10–p90 | Kills | Level | Bosses | Minis | Won |\n|---|---|---|---|---|---|---|---|';

it('balance simulation', { timeout: 3_600_000 }, () => {
  const out: string[] = [
    '# Balance results',
    '',
    `Generated by \`npm run balance\` (${RUNS} seeds per cell, cap ${CAP} s).`,
    '',
  ];
  const policies: Policy[] = ['newbie', 'smart'];
  out.push('## Policies (starting weapon: sword)', '', HEAD);
  const byPolicy = new Map<Policy, BotResult[]>();
  for (const policy of policies) {
    const rs: BotResult[] = [];
    for (let i = 0; i < RUNS; i++) rs.push(playRun({ seed: 1000 + i, policy, maxTime: CAP }));
    byPolicy.set(policy, rs);
    out.push(row(policy, rs));
  }
  // Death-time histogram for the smart bot.
  const smart = byPolicy.get('smart') ?? [];
  out.push('', '## Smart bot: how runs ended', '');
  for (const r of smart) {
    out.push(
      `- seed ${r.seed}: ${mmss(r.time)} ${r.dead ? 'died' : 'survived'}, lvl ${r.level}, kills ${r.kills}, bosses ${r.bossKills}, weapons ${r.weapons.join(' ')}`,
    );
  }
  // Card pick rates.
  const counts = new Map<string, number>();
  let total = 0;
  for (const r of [...smart, ...(byPolicy.get('newbie') ?? [])]) {
    for (const p of r.picks) {
      counts.set(p, (counts.get(p) ?? 0) + 1);
      total++;
    }
  }
  out.push('', '## Most picked cards (smart + newbie)', '');
  [...counts.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 25)
    .forEach(([k, v]) => out.push(`- ${k}: ${((100 * v) / Math.max(1, total)).toFixed(1)}%`));

  // Per-weapon survival (smart bot, that weapon as the only starter).
  const ids =
    WEAPON_FILTER === 'all' ? WEAPON_IDS : (WEAPON_FILTER.split(',') as typeof WEAPON_IDS);
  out.push('', '## Per starting weapon (smart bot)', '', HEAD);
  for (const id of ids) {
    const rs: BotResult[] = [];
    for (let i = 0; i < Math.max(3, Math.floor(RUNS / 2)); i++) {
      rs.push(playRun({ seed: 2000 + i, policy: 'smart', start: id, maxTime: CAP }));
    }
    out.push(row(id, rs));
  }
  writeFileSync('docs/BALANCE_RESULTS.md', out.join('\n') + '\n');
  console.log(out.join('\n'));
});
